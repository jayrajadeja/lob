func runGolden() []trade.Trade {
	b := book.New("G")
	g := gen.New(gen.Params{Seed: 99, Count: 200, Mid: 100, Tick: 1, MaxQty: 4, CancelProb: 0.0})
	var trades []trade.Trade
	for {
		a, ok := g.Next()
		if !ok {
			break
		}
		got, _ := b.Add(a.Order)
		trades = append(trades, got...)
	}
	return trades
}

